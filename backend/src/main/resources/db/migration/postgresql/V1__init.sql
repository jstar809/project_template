-- 초기 스키마 (PostgreSQL)
-- 주의: mysql/V1__init.sql 과 반드시 같은 내용을 같은 버전 번호로 유지한다.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    nickname      VARCHAR(20)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    last_login_at TIMESTAMP(6) WITH TIME ZONE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deleted_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_nickname UNIQUE (nickname)
);
CREATE INDEX idx_users_role_status ON users (role, status);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    user_agent VARCHAR(255),
    ip_address VARCHAR(45),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);

CREATE TABLE boards (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug               VARCHAR(30) NOT NULL,
    name               VARCHAR(50) NOT NULL,
    description        VARCHAR(255),
    read_permission    VARCHAR(20) NOT NULL,
    write_permission   VARCHAR(20) NOT NULL,
    comment_enabled    BOOLEAN     NOT NULL DEFAULT TRUE,
    attachment_enabled BOOLEAN     NOT NULL DEFAULT TRUE,
    active             BOOLEAN     NOT NULL DEFAULT TRUE,
    sort_order         INTEGER     NOT NULL DEFAULT 0,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by         BIGINT,
    deleted_at         TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_boards_slug UNIQUE (slug)
);
CREATE INDEX idx_boards_active_sort ON boards (active, sort_order);

CREATE TABLE posts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id      BIGINT       NOT NULL,
    author_id     BIGINT       NOT NULL,
    title         VARCHAR(200) NOT NULL,
    content       TEXT         NOT NULL,
    content_text  TEXT         NOT NULL,
    is_notice     BOOLEAN      NOT NULL DEFAULT FALSE,
    status        VARCHAR(20)  NOT NULL,
    view_count    BIGINT       NOT NULL DEFAULT 0,
    comment_count BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by    BIGINT,
    deleted_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_posts_board FOREIGN KEY (board_id) REFERENCES boards (id),
    CONSTRAINT fk_posts_author FOREIGN KEY (author_id) REFERENCES users (id)
);
CREATE INDEX idx_posts_board_list ON posts (board_id, deleted_at, status, is_notice, created_at);
CREATE INDEX idx_posts_author ON posts (author_id);
CREATE INDEX idx_posts_created_at ON posts (created_at);

CREATE TABLE comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT        NOT NULL,
    author_id  BIGINT        NOT NULL,
    parent_id  BIGINT,
    content    VARCHAR(1000) NOT NULL,
    status     VARCHAR(20)   NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by BIGINT,
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT fk_comments_parent FOREIGN KEY (parent_id) REFERENCES comments (id)
);
CREATE INDEX idx_comments_post ON comments (post_id, parent_id, created_at);
CREATE INDEX idx_comments_author ON comments (author_id);

CREATE TABLE files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key   VARCHAR(255) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    uploader_id   BIGINT       NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_files_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_files_uploader FOREIGN KEY (uploader_id) REFERENCES users (id)
);
CREATE INDEX idx_files_status_created ON files (status, created_at);

CREATE TABLE post_files (
    post_id    BIGINT      NOT NULL,
    file_id    BIGINT      NOT NULL,
    usage_type VARCHAR(20) NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    PRIMARY KEY (post_id, file_id),
    CONSTRAINT uk_post_files_file UNIQUE (file_id),
    CONSTRAINT fk_post_files_post FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT fk_post_files_file FOREIGN KEY (file_id) REFERENCES files (id)
);
